// Prebuild step: generates public/firebase-config.js from .env.local so the
// push service worker gets the Firebase web config without shipping keys in
// source control. Values are public-by-design but kept in one place.
//
// Missing vars → FIREBASE_CONFIG = null → the SW stays idle (no crash).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

function readEnv(key) {
  // Vercel/CI expose envs via process.env; local dev via .env.local.
  if (process.env[key]) return process.env[key];
  if (!existsSync('.env.local')) return undefined;
  const line = readFileSync('.env.local', 'utf8')
    .split(/\r?\n/)
    .find(l => l.trim().startsWith(key + '='));
  return line ? line.slice(key.length + 1).trim().replace(/^["']|["']$/g, '') : undefined;
}

const cfg = {
  apiKey: readEnv('VITE_FIREBASE_API_KEY'),
  authDomain: readEnv('VITE_FIREBASE_AUTH_DOMAIN'),
  projectId: readEnv('VITE_FIREBASE_PROJECT_ID'),
  messagingSenderId: readEnv('VITE_FIREBASE_MESSAGING_SENDER_ID'),
  appId: readEnv('VITE_FIREBASE_APP_ID'),
};

const complete = Object.values(cfg).every(v => v && v.length > 0);
const out = complete
  ? `// AUTO-GENERATED by scripts/generate-sw-config.mjs — do not edit.\nself.FIREBASE_CONFIG = ${JSON.stringify(cfg)};\n`
  : `// AUTO-GENERATED placeholder — Firebase keys not configured yet.\nself.FIREBASE_CONFIG = null;\n`;

writeFileSync('public/firebase-config.js', out);
console.log('[generate-sw-config] firebase-config.js:', complete ? 'configured' : 'placeholder (keys missing)');
